export function countUp(el, to, { decimals = 0, duration = 900, prefix = '', suffix = '' } = {}) {
  if (!el) return;
  const from = parseFloat(el.dataset.v || '0') || 0;
  el.dataset.v = to;
  const t0 = performance.now();
  const step = now => {
    const k = Math.min(1, (now - t0) / duration);
    const e = 1 - Math.pow(1 - k, 3);
    el.textContent = prefix + fmt(from + (to - from) * e, decimals) + suffix;
    if (k < 1) requestAnimationFrame(step);
  };
  requestAnimationFrame(step);
}

export function bindRange(input, out, format = v => v) {
  const sync = () => {
    const min = +input.min, max = +input.max;
    input.style.setProperty('--fill', `${((input.value - min) / (max - min)) * 100}%`);
    if (out) out.textContent = format(+input.value);
  };
  input.addEventListener('input', sync);
  sync();
  return sync;
}

