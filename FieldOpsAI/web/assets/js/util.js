export function hydrateIcons(root = document) {
  root.querySelectorAll('i[data-i]').forEach(el => {
    const t = document.createElement('template');
    t.innerHTML = icon(el.dataset.i);
    el.replaceWith(t.content.firstChild);
  });
}

