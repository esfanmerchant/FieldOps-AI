export class ApiError extends Error {
  constructor(message, details = [], status = 0) {
    super(message);
    this.details = details;
    this.status = status;
  }
}

export async function api(path, body) {
  const opts = body === undefined ? {} : { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(body) };
  let res;
  try {
    res = await fetch(path, opts);
  } catch {
    throw new ApiError('Cannot reach the FieldOps engine. Is the Python server running?');
  }
  const data = await res.json().catch(() => ({}));
  if (!res.ok) throw new ApiError(data.error || `Request failed (${res.status})`, data.details || [], res.status);
  return data;
}

export function toast(msg, type = 'info', ms = 3600) {
  const box = $('#toasts');
  const el = document.createElement('div');
  el.className = `toast ${type}`;
  el.innerHTML = icon(type === 'ok' ? 'checkCircle' : type === 'err' ? 'alert' : 'info') + `<span>${msg}</span>`;
  box.appendChild(el);
  setTimeout(() => { el.classList.add('out'); setTimeout(() => el.remove(), 320); }, ms);
}

